#!/bin/bash
# vault-update.sh - update this vault on demand (macOS/Linux): self-healing fetch + fast-forward, then the kit refresh, then the asset sync (<vault>/Assets, from the host share).
# Same steps the login agent/timer runs (it passes --quiet). Nothing runs every 15 minutes any more.
# Usage: bash vault-update.sh [--quiet] [--no-kit] [--no-assets] [--no-ai-vault] [--full-view on|off]
#        The companion AI Library Vault (next to this vault, folder ai-library-vault) is updated together with this vault by ai-vault-sync.sh; --no-ai-vault skips it.
#        bash vault-update.sh --set-view light|full   (switch only, no update, works offline; what /light-mode-on and /light-mode-off run)
#        bash vault-update.sh --clean [--yes] [--include-mine]   (what /vault-update-clean runs: exact copy of the main vault; without --yes it only prints the dry run)
# YOUR DATA IS KEPT: <vault>/My Research/, <vault>/Games/ (your per-game notes and Games/_Reusable) and any folder holding PROTECTED-RESEARCH.md are protected (git-excluded, never in a patch, never reset or cleaned). The normal update never deletes untracked files.
# Self-healing: the vault clone is READ-ONLY. If local changes or divergence block the fast-forward, the real changes are saved to
# <state>/local-changes-<timestamp>.patch (state: ~/.local/state/claudes-vault-sync, macOS ~/Library/Application Support/claudes-vault-sync; newest 5 kept)
# and the vault is reset to origin/main. CRLF-only noise is dropped silently.
# --full-view on: Obsidian indexes everything except Assets/ (slower; ~14,000 more notes). --full-view off: back to light mode. Survives updates (marker .full-view).
# Needs Tailscale for the asset sync (skips with one line when the share is unreachable). First run downloads about 2.7 GB of assets.
# Never commits or pushes. Do not edit this file in the vault; it is mastered on the PC. Always exits 0 unless git is missing.
# The body is one block so bash has read it all before the reset can replace this file.
{
NOAI=0; SETVIEW=""; QUIET=0; NOKIT=0; NOASSETS=0; FULLVIEW=""; CLEAN=0; YES=0; INCMINE=0
while [ $# -gt 0 ]; do case "$1" in --quiet) QUIET=1;; --no-kit) NOKIT=1;; --no-assets) NOASSETS=1;; --no-ai-vault) NOAI=1;; --full-view) shift; FULLVIEW="${1:-}";; --set-view) shift; SETVIEW="${1:-}";; --clean) CLEAN=1;; --yes) YES=1;; --include-mine) INCMINE=1;; esac; shift; done
VAULT="$(cd "$(dirname "${BASH_SOURCE[0]:-$0}")" && pwd)"
for p in /opt/homebrew/bin /usr/local/bin "$HOME/.local/bin"; do [ -d "$p" ] && PATH="$p:$PATH"; done
export PATH GIT_TERMINAL_PROMPT=0
if [ -n "${VAULT_STATE_DIR:-}" ]; then STATE="$VAULT_STATE_DIR"
elif [ "$(uname -s)" = Darwin ]; then STATE="$HOME/Library/Application Support/claudes-vault-sync"
else STATE="${XDG_STATE_HOME:-$HOME/.local/state}/claudes-vault-sync"; fi
GIT="$(command -v git || true)"
if [ -z "$GIT" ]; then echo "vault-update: git not found"; exit 1; fi
# --- vault-heal (same block in vault-update.sh, mac-sync-setup.sh, linux-sync-setup.sh) ---
# Self-healing update of the READ-ONLY vault clone. Never fails, never runs git clean. Prints at most one line.
# core.autocrlf/safecrlf off, fetch, fast-forward; if local changes or divergence block that, the real changes are saved to
# <state>/local-changes-<timestamp>.patch (+ untracked list; newest 5 kept) and the vault is reset to origin/main.
# Full view (marker <vault>/.full-view): after every update .obsidian/app.json gets userIgnoreFilters = ["Assets/"] only; never saved as a local change.
vault_json() { # $1 = mode (strip|set) ; reads JSON text on stdin, writes JSON text on stdout
  local PY="" c; for c in python3 python; do if command -v "$c" >/dev/null 2>&1 && "$c" -c 'import json' >/dev/null 2>&1; then PY="$(command -v "$c")"; break; fi; done
  if [ -n "$PY" ]; then
    "$PY" -c '
import sys, json
mode = sys.argv[1]
t = sys.stdin.read().strip() or "{}"
o = json.loads(t)
if mode == "strip":
    o.pop("userIgnoreFilters", None); print(json.dumps(o, sort_keys=True))
else:
    o["userIgnoreFilters"] = ["Assets/"]; print(json.dumps(o, indent=2, ensure_ascii=False))
' "$1"
  elif command -v node >/dev/null 2>&1; then
    node -e '
const m = process.argv[1]; let t = require("fs").readFileSync(0, "utf8").trim() || "{}"; const o = JSON.parse(t);
if (m === "strip") { delete o.userIgnoreFilters; const k = {}; Object.keys(o).sort().forEach(x => k[x] = o[x]); console.log(JSON.stringify(k)); }
else { o.userIgnoreFilters = ["Assets/"]; console.log(JSON.stringify(o, null, 2)); }
' "$1"
  else return 1; fi
}
vault_fullview_apply() { # $1 = vault
  [ -f "$1/.full-view" ] || return 0
  local F="$1/.obsidian/app.json" TMP
  mkdir -p "$1/.obsidian"; [ -f "$F" ] || echo '{}' > "$F"
  TMP="$(vault_json set < "$F" 2>/dev/null)" && [ -n "$TMP" ] && printf '%s\n' "$TMP" > "$F"
  return 0
}
# PROTECTED USER DATA: <vault>/My Research/ and every folder that holds PROTECTED-RESEARCH.md are added to .git/info/exclude on every run (git never treats them as
# removable), are never in a patch and never touched by reset. Untracked files are never removed by a normal update; it prints "N of your own files kept".
vault_protected() { # $1=git $2=vault ; prints protected dirs (relative, no trailing slash), 'My Research' first
  local G="$1" V="$2" REG="$2/.git/info/protected-folders.txt" d
  { echo 'My Research'; echo 'Games'   # Games = per-game communities + Games/_Reusable: always protected, never shipped by origin
    [ -f "$REG" ] && cat "$REG"
    "$G" -C "$V" -c core.quotepath=false ls-files -o --exclude-standard -- '*PROTECTED-RESEARCH.md' 2>/dev/null | sed -n 's#^\(.*\)/PROTECTED-RESEARCH\.md$#\1#p'
  } | awk 'NF && !seen[$0]++' | while IFS= read -r d; do
    case "$d" in "My Research/"*|"Games/"*) continue;; esac
    if [ "$d" = "My Research" ] || [ "$d" = "Games" ] || [ -f "$V/$d/PROTECTED-RESEARCH.md" ]; then echo "$d"; fi
  done
}
vault_protect() { # $1=git $2=vault ; sets PROT (newline list) and adds /<dir>/ lines to .git/info/exclude (idempotent)
  local V="$2" EX="$2/.git/info/exclude" REG="$2/.git/info/protected-folders.txt" d
  PROT="$(vault_protected "$1" "$2")"
  mkdir -p "$V/.git/info"
  printf '%s\n' "$PROT" | tail -n +3 > "$REG"; [ -s "$REG" ] || rm -f "$REG"
  while IFS= read -r d; do
    [ -n "$d" ] || continue
    grep -qxF "/$d/" "$EX" 2>/dev/null || echo "/$d/" >> "$EX"
  done <<EOF_PROT
$PROT
EOF_PROT
  return 0
}
vault_own_count() { # $1=git $2=vault ; number of your own files (untracked + inside protected folders)
  local G="$1" V="$2" n d c
  n="$("$G" -C "$V" ls-files -o --exclude-standard 2>/dev/null | wc -l | tr -d ' ')"
  while IFS= read -r d; do
    [ -n "$d" ] && [ -d "$V/$d" ] || continue
    c="$(find "$V/$d" -type f 2>/dev/null | wc -l | tr -d ' ')"; n=$((n + c))
  done <<EOF_PROT
$PROT
EOF_PROT
  echo "$n"
}
PUBLIC_NOTES_GIT="https://github.com/romangigliotti123-arch/vault-notes-01.git"   # set in the public copy by the site build: the GitHub repo that replaces the old website vault.git remote
vault_migrate_origin() { # $1=git $2=vault ; an origin on the old *.netlify.app/vault.git (the website only redirects now) is moved to the GitHub repo once
  [ -n "$PUBLIC_NOTES_GIT" ] || return 0
  case "$("$1" -C "$2" remote get-url origin 2>/dev/null)" in
    *.netlify.app/vault.git*) "$1" -C "$2" remote set-url origin "$PUBLIC_NOTES_GIT" 2>/dev/null && echo "vault-update: origin moved to $PUBLIC_NOTES_GIT";;
  esac
  return 0
}
vault_heal() { # $1=git $2=vault $3=state dir ; echoes one line when something notable happened
  local G="$1" V="$2" S="$3" T BASE TS P SAVED=0 CUR HEAD MSG=""
  "$G" -C "$V" config core.autocrlf false 2>/dev/null; "$G" -C "$V" config core.safecrlf false 2>/dev/null
  vault_migrate_origin "$G" "$V"
  vault_protect "$G" "$V"
  if ! "$G" -C "$V" fetch -q origin >/dev/null 2>&1; then MSG="vault-update: fetch failed (offline?), vault left as it is"
  else
    T=origin/main
    "$G" -C "$V" rev-parse -q --verify "$T" >/dev/null 2>&1 || { T='@{u}'; "$G" -C "$V" rev-parse -q --verify "$T" >/dev/null 2>&1 || T=""; }
    if [ -z "$T" ]; then MSG="vault-update: no upstream branch, vault left as it is"
    else
      if [ -f "$V/.full-view" ] && [ -f "$V/.obsidian/app.json" ]; then
        CUR="$(vault_json strip < "$V/.obsidian/app.json" 2>/dev/null)"; HEAD="$("$G" -C "$V" show HEAD:.obsidian/app.json 2>/dev/null | vault_json strip 2>/dev/null)"
        [ -n "$CUR" ] && [ "$CUR" = "$HEAD" ] && "$G" -C "$V" checkout -q -- .obsidian/app.json 2>/dev/null
      fi
      "$G" -C "$V" update-index -q --refresh >/dev/null 2>&1
      if "$G" -C "$V" diff HEAD --quiet >/dev/null 2>&1 && "$G" -C "$V" merge --ff-only -q "$T" >/dev/null 2>&1; then :
      else
        BASE="$("$G" -C "$V" merge-base HEAD "$T" 2>/dev/null)"; [ -n "$BASE" ] || BASE=HEAD
        mkdir -p "$S"; TS="$(date +%Y%m%d-%H%M%S)"; P="$S/local-changes-$TS.patch"
        if [ -n "$("$G" -C "$V" diff "$BASE" --ignore-cr-at-eol 2>/dev/null | head -c 1)" ]; then
          "$G" -C "$V" diff "$BASE" --binary > "$P" 2>/dev/null && SAVED=1
        fi
        "$G" -C "$V" -c core.quotepath=false ls-files --others --exclude-standard > "$S/local-changes-$TS.untracked.txt" 2>/dev/null
        [ -s "$S/local-changes-$TS.untracked.txt" ] || rm -f "$S/local-changes-$TS.untracked.txt"
        # untracked files that upstream now tracks would be overwritten by the reset: copy them aside first
        if [ -s "$S/local-changes-$TS.untracked.txt" ]; then
          LC_ALL=C sort "$S/local-changes-$TS.untracked.txt" > "$S/.u.$$"; "$G" -C "$V" -c core.quotepath=false ls-tree -r --name-only "$T" 2>/dev/null | LC_ALL=C sort > "$S/.t.$$"
          LC_ALL=C comm -12 "$S/.u.$$" "$S/.t.$$" | while IFS= read -r f; do mkdir -p "$(dirname "$S/collision-backup-$TS/$f")"; cp -p "$V/$f" "$S/collision-backup-$TS/$f" 2>/dev/null; done
          rm -f "$S/.u.$$" "$S/.t.$$"
        fi
        ls -1d "$S"/collision-backup-* 2>/dev/null | sort -r | tail -n +6 | while IFS= read -r f; do rm -rf "$f"; done
        ls -1 "$S"/local-changes-*.patch 2>/dev/null | sort -r | tail -n +6 | while IFS= read -r f; do rm -f "$f"; done
        ls -1 "$S"/local-changes-*.untracked.txt 2>/dev/null | sort -r | tail -n +6 | while IFS= read -r f; do rm -f "$f"; done
        if ! "$G" -C "$V" reset --hard -q "$T" >/dev/null 2>&1; then MSG="vault-update: could not reset the vault to the latest (left as it is)"
        elif [ "$SAVED" = 1 ]; then MSG="vault-update: local changes saved to $P; vault reset to the latest"; fi
      fi
    fi
  fi
  vault_fullview_apply "$V"
  [ -n "$MSG" ] && echo "$MSG"
  OWN="$(vault_own_count "$G" "$V" 2>/dev/null)"
  [ "${OWN:-0}" -gt 0 ] 2>/dev/null && echo "vault-update: $OWN of your own files kept (My Research, Games and your other files are never removed by /vault-update)"
  return 0
}
# --- end vault-heal ---
# --- vault-clean (only in vault-update.sh; logic for /vault-update-clean) ---
# --clean: make the vault an EXACT copy of origin/main: fetch, reset --hard, git clean -fd (never -x) with explicit excludes for everything protected
# (My Research/, every folder holding PROTECTED-RESEARCH.md, .full-view, Assets/, .obsidian/workspace*). DESTRUCTIVE: prints a dry run first and applies only with --yes
# (or after an interactive "yes"). Before deleting it saves a patch of your tracked edits + a list (clean-removed-<ts>.patch/.list.txt, newest 5) and copies the untracked
# files it will remove to <state>/clean-backup-<ts> (newest 3, max 500 MB; a bigger backup is skipped and said so). --include-mine also deletes My Research/ (only when its backup succeeded).
vc_show() { # $1=heading $2=text $3=max lines
  local n; n="$(printf '%s\n' "$2" | grep -c .)"
  echo "$1 ($n)"
  [ "$n" -gt 0 ] && printf '%s\n' "$2" | head -n "$3" | sed 's/^/  /'
  [ "$n" -gt "$3" ] && echo "  ... and $((n - $3)) more"
  return 0
}
vc_files() { find "$1" -type f 2>/dev/null | wc -l | tr -d ' '; }
vc_kb() { du -sk "$1" 2>/dev/null | cut -f1; }
vault_clean() { # $1=git $2=vault $3=state $4=yes(0|1) $5=include-mine(0|1) ; returns 0 when applied, 1 when not
  local G="$1" V="$2" S="$3" YES="$4" INC="$5" TAG=vault-update-clean T TS BK d i a CL LOCAL UP KEEP="" TOTALKB=0 KB OKB=1 MINEOK=1 NOTE="" MINE=0 REMOVED
  local -a EX
  "$G" -C "$V" config core.autocrlf false 2>/dev/null; "$G" -C "$V" config core.safecrlf false 2>/dev/null
  vault_protect "$G" "$V"
  if ! "$G" -C "$V" fetch -q origin >/dev/null 2>&1; then echo "$TAG: fetch failed (offline?), nothing changed"; return 1; fi
  T=origin/main
  "$G" -C "$V" rev-parse -q --verify "$T" >/dev/null 2>&1 || { echo "$TAG: no origin/main, nothing changed"; return 1; }
  "$G" -C "$V" update-index -q --refresh >/dev/null 2>&1
  while IFS= read -r d; do
    [ -n "$d" ] || continue
    if [ "$INC" = 1 ] && { [ "$d" = "My Research" ] || [ "${d#My Research/}" != "$d" ]; }; then continue; fi
    KEEP="${KEEP:+$KEEP, }$d/"
  done <<EOF_PROT
$PROT
EOF_PROT
  EX=(-e /.full-view -e /Assets/ -e '/.obsidian/workspace*')
  while IFS= read -r d; do
    [ -n "$d" ] || continue
    if [ "$INC" = 1 ] && { [ "$d" = "My Research" ] || [ "${d#My Research/}" != "$d" ]; }; then continue; fi
    EX+=(-e "/$d/")
  done <<EOF_PROT
$PROT
EOF_PROT
  CL="$("$G" -C "$V" -c core.quotepath=false clean -nd "${EX[@]}" 2>/dev/null | sed 's/^Would remove //')"
  LOCAL="$("$G" -C "$V" -c core.quotepath=false status --porcelain --untracked-files=no 2>/dev/null)"
  UP="$("$G" -C "$V" -c core.quotepath=false diff --name-status HEAD "$T" 2>/dev/null)"
  [ "$INC" = 1 ] && [ -d "$V/My Research" ] && MINE=1
  echo "$TAG: DRY RUN, nothing has been changed yet. Target: exact copy of $T ($("$G" -C "$V" rev-parse --short "$T"))."
  vc_show 'Your edits to tracked files that would be reset (saved to a patch first)' "$LOCAL" 30
  vc_show 'Files the update would change/add/remove to match the main vault' "$UP" 30
  vc_show 'Your own untracked files that would be deleted (copied to a backup first)' "$CL" 40
  echo "Kept untouched: ${KEEP:+$KEEP, }Assets/ (synced separately), .full-view, .obsidian/workspace*"
  if [ "$INC" = 1 ]; then
    if [ "$MINE" = 1 ]; then echo "WARNING --include-mine: My Research/ WILL BE DELETED too: $(vc_files "$V/My Research") files, $(( $(vc_kb "$V/My Research") / 1024 )) MB ($(ls -1A "$V/My Research" | tr '\n' ',' | sed 's/,$//; s/,/, /g')). A backup copy is made first; if the backup fails, My Research is kept."
    else echo "WARNING --include-mine: there is no My Research folder, nothing extra to delete."; fi
  fi
  if [ "$YES" != 1 ]; then
    if [ -t 0 ] && [ -t 1 ]; then
      printf 'Type yes to apply this clean update: '; read -r a
      [ "$a" = yes ] || { echo "$TAG: cancelled, nothing changed"; return 1; }
    else
      echo "$TAG: NOT APPLIED. Re-run with --yes to apply (bash \"$V/vault-update.sh\" --clean --yes)."; return 1
    fi
  fi
  # --- apply ---
  mkdir -p "$S"; TS="$(date +%Y%m%d-%H%M%S)"; BK="$S/clean-backup-$TS"
  [ -n "$LOCAL" ] && "$G" -C "$V" diff HEAD --binary > "$S/clean-removed-$TS.patch" 2>/dev/null
  { printf '%s\n' "$LOCAL" "$UP"; printf '%s\n' "$CL" | sed 's/^/untracked: /'; } | grep -v '^$' > "$S/clean-removed-$TS.list.txt"
  local ITEMS=""
  while IFS= read -r i; do i="${i%/}"; [ -n "$i" ] && ITEMS="${ITEMS}${i}"$'\n'; done <<EOF_CL
$CL
EOF_CL
  [ "$MINE" = 1 ] && ITEMS="${ITEMS}My Research"$'\n'
  while IFS= read -r i; do [ -n "$i" ] && { KB="$(vc_kb "$V/$i")"; TOTALKB=$((TOTALKB + ${KB:-0})); }; done <<EOF_IT
$ITEMS
EOF_IT
  if [ -z "$ITEMS" ]; then NOTE="no untracked files to back up"
  elif [ "$TOTALKB" -gt 512000 ]; then
    OKB=0; MINEOK=0; NOTE="backup of your untracked files SKIPPED: $((TOTALKB / 1024)) MB is over the 500 MB cap"; [ "$MINE" = 1 ] && NOTE="$NOTE; My Research is NOT deleted"
  else
    while IFS= read -r i; do
      [ -n "$i" ] || continue
      mkdir -p "$(dirname "$BK/$i")"; cp -R "$V/$i" "$BK/$i" 2>/dev/null
      if [ "$(vc_files "$V/$i")" != "$(vc_files "$BK/$i")" ]; then OKB=0; [ "$i" = "My Research" ] && MINEOK=0; fi
    done <<EOF_IT
$ITEMS
EOF_IT
    if [ "$OKB" = 1 ]; then NOTE="untracked files copied to $BK"; else NOTE="backup incomplete in $BK"; [ "$MINE" = 1 ] && [ "$MINEOK" = 0 ] && NOTE="$NOTE; My Research is NOT deleted"; fi
  fi
  ls -1 "$S"/clean-removed-*.patch 2>/dev/null | sort -r | tail -n +6 | while IFS= read -r f; do rm -f "$f"; done
  ls -1 "$S"/clean-removed-*.list.txt 2>/dev/null | sort -r | tail -n +6 | while IFS= read -r f; do rm -f "$f"; done
  ls -1d "$S"/clean-backup-* 2>/dev/null | sort -r | tail -n +4 | while IFS= read -r f; do rm -rf "$f"; done
  while [ "$(ls -1d "$S"/clean-backup-* 2>/dev/null | wc -l | tr -d ' ')" -gt 1 ] && [ "$(du -sk "$S"/clean-backup-* 2>/dev/null | awk '{s+=$1} END {print s+0}')" -gt 512000 ]; do
    rm -rf "$(ls -1d "$S"/clean-backup-* | sort | head -n 1)"
  done
  if ! "$G" -C "$V" reset --hard -q "$T" >/dev/null 2>&1; then echo "$TAG: could not reset the vault (left as it is, backups in $S)"; return 1; fi
  "$G" -C "$V" clean -fdq "${EX[@]}" >/dev/null 2>&1
  REMOVED="$(printf '%s\n' "$CL" | grep -c .)"
  if [ "$MINE" = 1 ] && [ "$MINEOK" = 1 ]; then rm -rf "$V/My Research"; NOTE="$NOTE. My Research deleted (backup kept)"; fi
  vault_fullview_apply "$V"
  echo "$TAG: vault is now an exact copy of $T ($("$G" -C "$V" rev-parse --short HEAD)); removed $REMOVED untracked item(s); $NOTE; tracked-edit patch + list in $S (clean-removed-$TS.*)."
  return 0
}
# --- end vault-clean ---

if [ -n "$SETVIEW" ]; then # switch-only (/light-mode-on, /light-mode-off): no fetch, no update, no kit, no assets; works offline
  if [ "$SETVIEW" = full ]; then
    mkdir -p "$VAULT/.git/info"; grep -qxF '/.full-view' "$VAULT/.git/info/exclude" 2>/dev/null || echo '/.full-view' >> "$VAULT/.git/info/exclude"
    echo 'full view on (vault-update.sh --set-view light to undo)' > "$VAULT/.full-view"; vault_fullview_apply "$VAULT"
    echo 'Light mode off (full view): everything except Assets visible. Slower. Reopen Obsidian.'
  else
    rm -f "$VAULT/.full-view"; "$GIT" -C "$VAULT" checkout -q -- .obsidian/app.json 2>/dev/null
    echo 'Light mode on: Imported, Library, Assets and source notes hidden. Reopen Obsidian.'
  fi
  [ "$NOAI" = 0 ] && [ -f "$VAULT/ai-vault-sync.sh" ] && { bash "$VAULT/ai-vault-sync.sh" --set-view "$SETVIEW" || true; }
  exit 0
fi
if [ "$FULLVIEW" = on ]; then
  mkdir -p "$VAULT/.git/info"; grep -qxF '/.full-view' "$VAULT/.git/info/exclude" 2>/dev/null || echo '/.full-view' >> "$VAULT/.git/info/exclude"
  echo 'full view on (vault-update.sh --full-view off to undo)' > "$VAULT/.full-view"
elif [ "$FULLVIEW" = off ]; then
  rm -f "$VAULT/.full-view"; "$GIT" -C "$VAULT" checkout -q -- .obsidian/app.json 2>/dev/null
fi
BEFORE="$("$GIT" -C "$VAULT" rev-parse --short HEAD 2>/dev/null)"
[ "$INCMINE" = 1 ] && [ "$CLEAN" = 0 ] && echo "vault-update: --include-mine only works together with --clean, ignored"
if [ "$CLEAN" = 1 ]; then vault_clean "$GIT" "$VAULT" "$STATE" "$YES" "$INCMINE" || exit 0; MSG=""
else MSG="$(vault_heal "$GIT" "$VAULT" "$STATE")"; fi
AFTER="$("$GIT" -C "$VAULT" rev-parse --short HEAD 2>/dev/null)"
[ -n "$MSG" ] && echo "$MSG"
if [ "$BEFORE" != "$AFTER" ]; then echo "vault-update: vault updated $BEFORE -> $AFTER"
elif [ "$QUIET" = 0 ]; then echo "vault-update: vault already up to date ($AFTER)"; fi
if [ -f "$VAULT/.full-view" ]; then echo "vault-update: full view ON (Obsidian indexes everything except Assets/; slower). Switch back: bash vault-update.sh --full-view off"
else echo "vault-update: light mode (default; Imported/, Library/ and Assets/ are not indexed by Obsidian). Full view: bash vault-update.sh --full-view on"; fi
if [ -f "$VAULT/claude-kit/kit-refresh.sh" ]; then
  [ "$NOKIT" = 1 ] && export CLAUDE_KIT_SKIP=1
  [ "$NOASSETS" = 1 ] && export CLAUDE_ASSETS_SKIP=1
  bash "$VAULT/claude-kit/kit-refresh.sh"
fi
# companion AI Library Vault: updated together with this vault (own clone next to it; self-healing, protected My Research); never fails the update
if [ "$NOAI" = 0 ] && [ -f "$VAULT/ai-vault-sync.sh" ]; then
  AIARGS=(); [ "$QUIET" = 1 ] && AIARGS+=(--quiet); [ -n "$FULLVIEW" ] && AIARGS+=(--full-view "$FULLVIEW")
  bash "$VAULT/ai-vault-sync.sh" "${AIARGS[@]}" || echo "vault-update: AI Library Vault step failed (non-fatal)"
fi
[ "$QUIET" = 0 ] && echo "vault-update: done"
exit 0
}
