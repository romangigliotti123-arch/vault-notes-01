#!/usr/bin/env python3
"""hookgen.py - write and check the local pre-commit hook that runs the kit's Luau checks. Stdlib only.

  python hookgen.py gen <project-dir> [--check-script PATH]   writes <project-dir>/.githooks/pre-commit
  python hookgen.py check <hook-file>                         verifies an existing hook
  python hookgen.py --selftest

The hook runs luau-check.sh (stylua --check, selene, luau-lsp) on STAGED .luau files only. Exit codes of luau-check.sh: 0 pass,
1 a check failed -> the commit is blocked, 2 no tool installed -> the commit is allowed but a loud UNCHECKED line is printed
(a missing tool is never reported as a pass). Enable once with: git config core.hooksPath .githooks . The hook never installs
anything and never calls the network. Exit 0 ok, 1 on a bad hook.
"""
import os
import stat
import sys
import tempfile

HOOK = """#!/usr/bin/env bash
# pre-commit: static Luau checks on staged files. Generated by hookgen.py; enable with: git config core.hooksPath .githooks
CHECK="${LUAU_CHECK:-%(check)s}"
files=$(git diff --cached --name-only --diff-filter=ACM | grep -E '\\.luau$' || true)
[ -z "$files" ] && exit 0
if [ ! -f "$CHECK" ]; then
  echo "UNCHECKED: luau-check.sh not found at $CHECK (set LUAU_CHECK); commit allowed, nothing was verified"
  exit 0
fi
bash "$CHECK" $files
rc=$?
if [ $rc -eq 1 ]; then
  echo "BLOCKED: a Luau check failed; fix it or ask the owner before bypassing"
  exit 1
fi
if [ $rc -eq 2 ]; then
  echo "UNCHECKED: no check tools installed (run rokit install); commit allowed, nothing was verified"
fi
exit 0
"""


def check_hook(text):
    errs = []
    if not text.startswith("#!"):
        errs.append("no shebang")
    if "luau-check.sh" not in text and "LUAU_CHECK" not in text:
        errs.append("does not call luau-check.sh")
    if "--cached" not in text:
        errs.append("does not limit itself to staged files (git diff --cached)")
    if "exit 1" not in text:
        errs.append("never blocks (no exit 1 path)")
    if "UNCHECKED" not in text:
        errs.append("a missing tool would be reported silently (need an UNCHECKED line)")
    if "--no-verify" in text:
        errs.append("advises --no-verify")
    return errs


def gen(project, check_script):
    d = os.path.join(project, ".githooks")
    os.makedirs(d, exist_ok=True)
    p = os.path.join(d, "pre-commit")
    with open(p, "w", encoding="utf-8", newline="\n") as f:
        f.write(HOOK % {"check": check_script.replace("\\", "/")})
    try:
        os.chmod(p, os.stat(p).st_mode | stat.S_IXUSR)
    except OSError:
        pass
    return p


def selftest():
    d = tempfile.mkdtemp()
    p = gen(d, ".rbx/claude-kit/tools/roblox-project-template/luau-check.sh")
    t = open(p, encoding="utf-8").read()
    assert check_hook(t) == [], check_hook(t)
    assert "\r" not in t
    assert any("staged" in e for e in check_hook(t.replace("--cached", "HEAD")))
    assert any("UNCHECKED" in e for e in check_hook(t.replace("UNCHECKED", "info")))
    assert any("blocks" in e for e in check_hook(t.replace("exit 1", "exit 0")))
    print("selftest ok (4 cases)")
    return 0


def main(argv):
    if argv[:1] == ["--selftest"]:
        return selftest()
    if len(argv) >= 2 and argv[0] == "gen":
        cs = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "..", "..", "tools", "roblox-project-template", "luau-check.sh"))   # the installed kit: <vault>/.rbx/claude-kit/tools/... (an absolute path, the hook runs in the game's own folder)
        if not os.path.isfile(cs):
            cs = ".rbx/claude-kit/tools/roblox-project-template/luau-check.sh"
        if "--check-script" in argv:
            cs = argv[argv.index("--check-script") + 1]
        print("wrote", gen(argv[1], cs))
        return 0
    if len(argv) == 2 and argv[0] == "check":
        errs = check_hook(open(argv[1], encoding="utf-8").read())
        print("PASS" if not errs else "FAIL: " + "; ".join(errs))
        return 1 if errs else 0
    print(__doc__)
    return 1


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
