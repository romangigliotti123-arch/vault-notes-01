#!/usr/bin/env python3
"""build_inline.py: builds the two generated Luau files of rbx-placement from their sources.
  Placement.luau       = PlacementCore.luau (inlined) + adapter.src + `return Placement`   (the module: copy to src/shared/Placement.luau, or paste before your own code)
  placement_run.luau   = PlacementCore.luau (inlined) + adapter.src + runner.src            (one file for execute_luau: edit CONFIG at the top of the runner part)
  python build_inline.py          write both
  python build_inline.py --check  exit 1 if either is out of date (run stylua on the results first when you wrote them)
After editing PlacementCore.luau, adapter.src or runner.src: run `stylua PlacementCore.luau` (the sources), then this (it formats the generated files with stylua when it is installed).
"""
import os
import shutil
import subprocess
import sys

d = os.path.dirname(os.path.abspath(__file__))


def rd(n):
    return open(os.path.join(d, n), encoding="utf-8").read()


core = rd("PlacementCore.luau").replace("--!strict\n", "", 1).rstrip("\n")
adapter = rd("adapter.src").rstrip("\n")
runner = rd("runner.src").rstrip("\n")
head = "--!strict\n-- GENERATED by build_inline.py from PlacementCore.luau + adapter.src%s. Edit those, not this file.\n"
body = "local PlacementCore = (function()\n" + core + "\nend)()\nlocal Core = PlacementCore\n\n" + adapter + "\n"
outs = {
    "Placement.luau": (head % "") + body + "\nreturn Placement\n",
    "placement_run.luau": (head % " + runner.src") + body + "\n" + runner + "\n",
}


def _kit_systems():
    cur = d
    for _ in range(8):
        cand = os.path.join(cur, "systems")
        if os.path.exists(os.path.join(cand, "stylua.toml")):
            return cand
        cur = os.path.dirname(cur)
    return None


def styled(text):
    """Run stylua on the generated text (so --check compares like with like). Runs inside the kit's systems folder (Rokit needs its rokit.toml and
    stylua reads stylua.toml from the working directory). Without stylua or the folder the text is used as it is."""
    sysdir = _kit_systems()
    exe = shutil.which("stylua") or os.path.join(os.path.expanduser("~"), ".rokit", "bin", "stylua" + (".exe" if os.name == "nt" else ""))
    if not sysdir or not (shutil.which("stylua") or os.path.exists(exe)):
        return text
    for _ in range(4):  # stylua is not always idempotent on the first pass for nested blocks: run until it settles
        r = subprocess.run([exe, "-"], input=text, capture_output=True, text=True, encoding="utf-8", cwd=sysdir)
        if r.returncode != 0 or not r.stdout:
            return text
        if r.stdout == text:
            break
        text = r.stdout
    return text


bad = False
for name, text in outs.items():
    text = styled(text)
    p = os.path.join(d, name)
    if "--check" in sys.argv:
        cur = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
        if cur != text:
            bad = True
        continue
    open(p, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", p)
if "--check" in sys.argv:
    sys.exit(1 if bad else 0)
