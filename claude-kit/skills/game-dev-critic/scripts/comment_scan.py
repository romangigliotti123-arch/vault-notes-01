#!/usr/bin/env python3
"""comment_scan.py: comment-density check of the code-quality review (stdlib only).

  python comment_scan.py <folder | file.luau ...> [--game ID] [--scorer critic|builder] [--write GAME_FOLDER] [--strict] [--all-files] [--include-defs]

The vault rule: NO COMMENTS BY DEFAULT in game code; a one-line comment only for WHY (engine quirk, ordering, replication timing, physics ownership), never WHAT.
Scans .lua / .luau files and counts, per file and in total: code lines, comment lines, block comments (--[[ ]]), trailing comments on code lines and STRAY
comment lines (everything that is not allowed). Allowed, not counted as stray: directives (--!strict, --!native, --!optimize, --!nolint, stylua:/selene: switches,
--#METADATA#), a license/copyright header at the top of a file (third-party code), a "GENERATED by" header, and a ONE-line comment that explains why
(heuristic: it contains because, so that, otherwise, must, quirk, engine, replicat or order). A run of two or more comment lines is never a why-line.
Skipped: *.d.luau definition files (use --include-defs), Packages/, node_modules/, .git/, benchmarks/.

Output: JSON in the format of the other gates (kind, scorer, pass_min, result, checks, reasons, failing, counts, files, suggested_fix). With --write GAME_FOLDER the record
is saved as GAME_FOLDER/comment-scan/gate.json, where game-dev-benchmark's scorecard.py finds it by itself (gate "comment-scan", weight 10 like every other extra gate).
It is a SCORED finding, never a hard block: the exit code is 0 unless --strict is given (the kit tests use it).
Checks (0-10, pass mark 7): CM1 stray lines per code line (0 = 10, 1% = 8, 5% or more = 0), CM2 trailing narration comments, CM3 block comments.
"""
import json
import os
import re
import sys
import time

BS = chr(92)
WHY = re.compile(r"because|so that|otherwise|must|quirk|engine|replicat|order", re.I)
TOOL = re.compile(r"^--\s*(stylua:|selene:|luau-lsp|@)")
LICENSE = re.compile(r"licen[sc]e|copyright|spdx|\(c\)|permission is hereby granted", re.I)
GENERATED = re.compile(r"^--\s*GENERATED\b")
SKIP_DIRS = {"packages", "node_modules", ".git", "benchmarks", "__pycache__", "_packages"}
PASS_MIN = 7.0
FIX = "delete the comment (keep only a one-line WHY for an engine quirk, ordering, replication timing or physics ownership)"


def _skip_str(src, i, q):
    n = len(src)
    i += 1
    while i < n and src[i] != q:
        i += 2 if src[i] == BS else 1
    return i + 1


def comments(src):
    """-> [(start, end, kind)] of every comment, skipping strings, long strings and backtick strings."""
    out = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        if c == "-" and src.startswith("--", i):
            m = re.match(r"--\[(=*)\[", src[i:i + 40])
            if m:
                close = "]" + m.group(1) + "]"
                j = src.find(close, i + m.end())
                j = n if j < 0 else j + len(close)
                out.append((i, j, "block"))
            else:
                j = src.find("\n", i)
                j = n if j < 0 else j
                out.append((i, j, "line"))
            i = j
            continue
        if c in "\"'":
            i = _skip_str(src, i, c)
            continue
        if c == "[":
            m = re.match(r"\[(=*)\[", src[i:i + 40])
            if m:
                close = "]" + m.group(1) + "]"
                j = src.find(close, i + m.end())
                i = n if j < 0 else j + len(close)
                continue
        if c == "`":
            i += 1
            while i < n and src[i] != "`":
                if src[i] == BS:
                    i += 2
                    continue
                if src[i] == "{":
                    depth = 1
                    i += 1
                    while i < n and depth:
                        if src[i] == "{":
                            depth += 1
                        elif src[i] == "}":
                            depth -= 1
                        elif src[i] in "\"'":
                            i = _skip_str(src, i, src[i]) - 1
                        i += 1
                    continue
                i += 1
            i += 1
            continue
        i += 1
    return out


def scan_text(src):
    """-> per-file counts"""
    lines = src.split("\n")
    starts = []
    pos = 0
    for ln in lines:
        starts.append(pos)
        pos += len(ln) + 1

    def line_of(p):
        lo, hi = 0, len(starts) - 1
        while lo < hi:
            mid = (lo + hi + 1) // 2
            if starts[mid] <= p:
                lo = mid
            else:
                hi = mid - 1
        return lo

    cs = comments(src)
    mask = [list(l) for l in lines]
    info = []
    for (s, e, kind) in cs:
        text = src[s:e]
        l0 = line_of(s)
        l1 = line_of(max(s, e - 1))
        for li in range(l0, l1 + 1):
            a = max(s, starts[li]) - starts[li]
            b = min(e, starts[li] + len(lines[li])) - starts[li]
            for k in range(a, b):
                mask[li][k] = " "
        info.append((s, e, kind, text, l0, l1))
    code_lines = set()
    for li, m in enumerate(mask):
        if "".join(m).strip():
            code_lines.add(li)
    header_end = -1
    for (s, e, kind, text, l0, l1) in info:
        if l0 > 25:
            break
        if LICENSE.search(text):
            header_end = max(header_end, l1)
    res = dict(code=len(code_lines), comment=0, allowed=0, stray=0, trailing=0, blocks=0, stray_blocks=0, stray_trailing=0, examples=[])
    solo = []
    for idx, (s, e, kind, text, l0, l1) in enumerate(info):
        trailing = l0 in code_lines
        if kind == "line" and not trailing and not text.startswith("--!") and not TOOL.match(text):
            solo.append((idx, l0))
    run_len = {}
    comment_only = {l0: idx for idx, l0 in solo}
    for idx, l0 in solo:
        a = l0
        while (a - 1) in comment_only:
            a -= 1
        b = l0
        while (b + 1) in comment_only:
            b += 1
        run_len[idx] = b - a + 1
    for idx, (s, e, kind, text, l0, l1) in enumerate(info):
        ls = starts[l0]
        at_line_start = src[ls:s].strip() == ""
        nlines = l1 - l0 + 1
        if text.startswith("--!") and at_line_start:
            continue
        if TOOL.match(text) or text.startswith("--#METADATA#"):
            continue
        if l0 <= header_end:
            continue
        res["comment"] += nlines
        trailing = l0 in code_lines
        if kind == "block":
            res["blocks"] += 1
            res["stray_blocks"] += 1
            res["stray"] += nlines
            if len(res["examples"]) < 5:
                res["examples"].append((l0 + 1, "block", text.strip().split("\n")[0][:100]))
            continue
        if GENERATED.match(text) and not trailing:
            res["allowed"] += 1
            continue
        one_line = (not trailing and run_len.get(idx, 1) == 1) or trailing
        if WHY.search(text) and one_line:
            res["allowed"] += 1
            continue
        res["stray"] += 1
        if trailing:
            res["trailing"] += 1
            res["stray_trailing"] += 1
        if len(res["examples"]) < 5:
            res["examples"].append((l0 + 1, "trailing" if trailing else "line", text.strip()[:100]))
    return res


def files_under(paths, include_defs=False):
    out = []
    for p in paths:
        if os.path.isfile(p):
            out.append(p)
            continue
        for d, dn, fn in os.walk(p):
            dn[:] = sorted(x for x in dn if x.lower() not in SKIP_DIRS)
            for f in sorted(fn):
                if f.endswith((".lua", ".luau")) and (include_defs or not f.endswith(".d.luau")):
                    out.append(os.path.join(d, f))
    return out


def build(paths, game=None, scorer="critic", include_defs=False, base=None):
    files = []
    tot = dict(code=0, comment=0, allowed=0, stray=0, trailing=0, blocks=0)
    failing = []
    stray_trailing = 0
    stray_blocks = 0
    for f in files_under(paths, include_defs):
        try:
            src = open(f, encoding="utf-8", errors="replace").read()
        except OSError:
            continue
        r = scan_text(src.replace("\r\n", "\n"))
        rel = os.path.relpath(f, base) if base else f
        rel = rel.replace(os.sep, "/")
        code = max(r["code"], 1)
        files.append(dict(path=rel, code=r["code"], comment=r["comment"], allowed=r["allowed"], stray=r["stray"], trailing=r["trailing"],
                          blocks=r["blocks"], density=round(r["comment"] / code, 3), stray_density=round(r["stray"] / code, 3)))
        for k in tot:
            tot[k] += r[k]
        stray_trailing += r["stray_trailing"]
        stray_blocks += r["stray_blocks"]
        for (ln, kind, text) in r["examples"][:2]:
            failing.append(dict(path="%s:%d" % (rel, ln), check="CM3" if kind == "block" else ("CM2" if kind == "trailing" else "CM1"),
                                found=text, fix="delete the comment"))
    ratio = tot["stray"] / max(tot["code"], 1)
    cm1 = 10.0 if tot["stray"] == 0 else max(0.0, round(10.0 - ratio * 200.0, 1))
    cm2 = 10.0 if stray_trailing == 0 else 8.0 if stray_trailing <= 2 else 6.0 if stray_trailing <= 5 else 3.0
    cm3 = 10.0 if stray_blocks == 0 else 8.0 if stray_blocks == 1 else 5.0 if stray_blocks <= 3 else 2.0
    checks = {"CM1": cm1, "CM2": cm2, "CM3": cm3}
    result = "pass" if min(checks.values()) >= PASS_MIN else "fail"
    reasons = []
    if tot["stray"]:
        reasons.append("%d stray comment lines over %d code lines (%.1f%%); the rule is no comments by default" % (tot["stray"], tot["code"], ratio * 100))
    if stray_trailing:
        reasons.append("%d trailing narration comments" % stray_trailing)
    if stray_blocks:
        reasons.append("%d block comments" % stray_blocks)
    worst = sorted(files, key=lambda x: -x["stray"])[:5]
    rec = dict(kind="comment-scan", scorer=scorer, game=game, severity="low", pass_min=PASS_MIN, result=result, checks=checks, reasons=reasons,
               failing=failing[:20], counts=dict(files=len(files), code_lines=tot["code"], comment_lines=tot["comment"], allowed_lines=tot["allowed"],
                                                 stray_lines=tot["stray"], trailing=stray_trailing, block_comments=stray_blocks,
                                                 density=round(tot["comment"] / max(tot["code"], 1), 3), stray_density=round(ratio, 3)),
               worst_files=[dict(path=w["path"], stray=w["stray"]) for w in worst if w["stray"]], files=files,
               suggested_fix=FIX if tot["stray"] else "none", time=time.strftime("%Y-%m-%dT%H:%M:%S"))
    return rec


def main(argv):
    if not argv or argv[0] in ("-h", "--help"):
        print(__doc__)
        return 0
    paths, opts = [], {"game": None, "scorer": "critic", "write": None}
    flags = set()
    i = 0
    while i < len(argv):
        a = argv[i]
        if a in ("--game", "--scorer", "--write"):
            opts[a[2:]] = argv[i + 1]
            i += 2
            continue
        if a.startswith("--"):
            flags.add(a)
        else:
            paths.append(a)
        i += 1
    if not paths:
        print("give a folder or files", file=sys.stderr)
        return 2
    rec = build(paths, opts["game"], opts["scorer"], "--include-defs" in flags, base=paths[0] if os.path.isdir(paths[0]) else None)
    if opts["write"]:
        d = os.path.join(opts["write"], "comment-scan")
        os.makedirs(d, exist_ok=True)
        with open(os.path.join(d, "gate.json"), "w", encoding="utf-8", newline="\n") as fh:
            json.dump(rec, fh, indent=1)
            fh.write("\n")
    out = dict(rec)
    if "--all-files" not in flags:
        out["files"] = [f for f in rec["files"] if f["stray"]]
    print(json.dumps(out, indent=1))
    return 1 if ("--strict" in flags and rec["counts"]["stray_lines"]) else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
