#!/usr/bin/env python3
"""build_inline.py: builds the generated Luau files of rbx-lighting from their sources.
  LightingData.luau   = presets.json as a Luau table (the pure core requires it)
  LightingKit.luau    = LightingData + LightingCore.luau (inlined) + adapter.src + `return LightingKit`   (the module: copy to src/shared/LightingKit.luau, or paste before your code)
  lighting_run.luau   = the same + runner.src                                                          (one file for execute_luau: edit CONFIG at the top of the runner part)
  python build_inline.py          write all three
  python build_inline.py --check  exit 1 if any is out of date (run stylua on the results first when you wrote them)
After editing presets.json, LightingCore.luau, adapter.src or runner.src: run `stylua LightingCore.luau` (the source), then this (it formats the generated files with stylua when it is installed).
"""
import json
import os
import re
import shutil
import subprocess
import sys

d = os.path.dirname(os.path.abspath(__file__))


def rd(n):
    return open(os.path.join(d, n), encoding="utf-8").read()


IDENT = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in", "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while", "continue", "type"}


def lua(v):
    if v is True:
        return "true"
    if v is False:
        return "false"
    if v is None:
        return "nil"
    if isinstance(v, int):
        return str(v)
    if isinstance(v, float):
        return repr(v)
    if isinstance(v, str):
        assert v.isascii(), "presets.json must stay ASCII: " + v
        return json.dumps(v)
    if isinstance(v, list):
        return "{ " + ", ".join(lua(x) for x in v) + " }"
    if isinstance(v, dict):
        items = []
        for k, x in v.items():
            key = k if IDENT.match(k) and k not in KEYWORDS else "[%s]" % json.dumps(k)
            items.append("%s = %s" % (key, lua(x)))
        return "{ " + ", ".join(items) + " }"
    raise TypeError(type(v))


data = json.loads(rd("presets.json"))
data_src = (
    "--!strict\n-- GENERATED by build_inline.py from presets.json. Edit presets.json, not this file.\n"
    "local LightingData: { [string]: any } = %s\n\nreturn LightingData\n" % lua({k: v for k, v in data.items() if k != "note"})
)
core = rd("LightingCore.luau").replace("--!strict\n", "", 1).rstrip("\n")
data_inline = data_src.replace("--!strict\n", "", 1).rstrip("\n")
assert 'local Data = require("./LightingData")' in core
core = core.replace('local Data = require("./LightingData")', "local Data = (function()\n" + data_inline + "\nend)()")
adapter = rd("adapter.src").rstrip("\n")
runner = rd("runner.src").rstrip("\n")
head = "--!strict\n-- GENERATED by build_inline.py from presets.json + LightingCore.luau + adapter.src%s. Edit those, not this file.\n"
body = "local LightingCore = (function()\n" + core + "\nend)()\nlocal Core = LightingCore\n\n" + adapter + "\n"
outs = {
    "LightingData.luau": data_src,
    "LightingKit.luau": (head % "") + body + "\nreturn LightingKit\n",
    "lighting_run.luau": (head % " + runner.src") + body + "\n" + runner + "\n",
}


def _kit_systems():
    cur = d
    for _ in range(8):
        cand = os.path.join(cur, "systems")
        if os.path.exists(os.path.join(cand, "stylua.toml")):
            return cand
        cur = os.path.dirname(cur)
    return None


def styled(text):
    """Run stylua on the generated text (so --check compares like with like). Runs inside the kit's systems folder (Rokit needs its rokit.toml and
    stylua reads stylua.toml from the working directory). Without stylua or the folder the text is used as it is."""
    sysdir = _kit_systems()
    exe = shutil.which("stylua") or os.path.join(os.path.expanduser("~"), ".rokit", "bin", "stylua" + (".exe" if os.name == "nt" else ""))
    if not sysdir or not (shutil.which("stylua") or os.path.exists(exe)):
        return text
    for _ in range(4):  # stylua is not always idempotent on the first pass for nested blocks: run until it settles
        r = subprocess.run([exe, "-"], input=text, capture_output=True, text=True, encoding="utf-8", cwd=sysdir)
        if r.returncode != 0 or not r.stdout:
            return text
        if r.stdout == text:
            break
        text = r.stdout
    return text


bad = False
for name, text in outs.items():
    text = styled(text)
    p = os.path.join(d, name)
    if "--check" in sys.argv:
        cur = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
        if cur != text:
            bad = True
            print("out of date:", name)
        continue
    open(p, "w", encoding="utf-8", newline="\n").write(text)
    print("wrote", p)
if "--check" in sys.argv:
    sys.exit(1 if bad else 0)
