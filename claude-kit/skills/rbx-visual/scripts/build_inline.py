#!/usr/bin/env python3
"""build_inline.py: ui_overlap.luau = Overlap.luau (inlined) + collect.src, so one file runs in execute_luau (no require).
  python build_inline.py          write ui_overlap.luau
  python build_inline.py --check  exit 1 if ui_overlap.luau is out of date (run stylua on the result first when you wrote it)
After editing Overlap.luau or collect.src: run this, then `stylua` on ui_overlap.luau.
"""
import os
import sys

d = os.path.dirname(os.path.abspath(__file__))
ov = open(os.path.join(d, "Overlap.luau"), encoding="utf-8").read().replace("--!strict\n", "", 1)
co = open(os.path.join(d, "collect.src"), encoding="utf-8").read().replace("--!strict\n", "", 1)
head = "--!strict\n-- GENERATED by build_inline.py from Overlap.luau + collect.src. Edit those two, not this file.\n"
ov = ov.replace("\nreturn Overlap\n", "\n").rstrip("\n")
out = head + ov + "\n\n" + co
p = os.path.join(d, "ui_overlap.luau")
if "--check" in sys.argv:
    cur = open(p, encoding="utf-8").read() if os.path.exists(p) else ""
    sys.exit(0 if cur == out else 1)
open(p, "w", encoding="utf-8", newline="\n").write(out)
print("wrote", p)
