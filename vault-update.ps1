if ($m) { Write-Output $m }
if ($before -ne $after) { Write-Output "rbx-update: vault updated $before -> $after" }
elseif (-not $Quiet) { Write-Output "rbx-update: vault already up to date ($after)" }
if (Test-Path -LiteralPath $marker) { Write-Output 'rbx-update: full view ON (Obsidian indexes everything except Assets/; slower). Switch back: vault-update.ps1 -FullView off' }
else { Write-Output 'rbx-update: light mode (default; Imported/, Library/ and Assets/ are not indexed by Obsidian). Full view: vault-update.ps1 -FullView on' }
$kr = Join-Path $vault 'claude-kit\kit-refresh.ps1'
if (Test-Path -LiteralPath $kr) {
  if ($NoKit) { $env:CLAUDE_KIT_SKIP = '1' }
  if ($NoAssets) { $env:CLAUDE_ASSETS_SKIP = '1' }
  & powershell -NoProfile -ExecutionPolicy Bypass -File $kr
}
# companion AI Library Vault: updated together with this vault (own clone next to it; self-healing, protected My Research); never fails the update
if (-not $NoAiVault) {
  $aiS = Join-Path $vault 'ai-vault-sync.ps1'
  if (Test-Path -LiteralPath $aiS) {
