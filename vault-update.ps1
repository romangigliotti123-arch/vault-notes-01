    Write-Output 'Light mode off (full view): everything except Assets visible. Slower. Reopen Obsidian.'
    if (-not $NoAiVault) { $aiS = Join-Path $vault 'ai-vault-sync.ps1'; if (Test-Path -LiteralPath $aiS) { try { & powershell -NoProfile -ExecutionPolicy Bypass -File $aiS -SetView full } catch { } } }
  } else {
    try { Remove-Item -LiteralPath $marker -Force -ErrorAction SilentlyContinue; & $git -C $vault checkout -q -- .obsidian/app.json 2>$null | Out-Null } catch { }
    Write-Output 'Light mode on: Imported, Library, Assets and source notes hidden. Reopen Obsidian.'
    if (-not $NoAiVault) { $aiS = Join-Path $vault 'ai-vault-sync.ps1'; if (Test-Path -LiteralPath $aiS) { try { & powershell -NoProfile -ExecutionPolicy Bypass -File $aiS -SetView light } catch { } } }
  }
  exit 0
}
if ($FullView -eq 'on') { try { Add-GitExclude $vault '/.full-view'; Set-Content -LiteralPath $marker -Value 'full view on (rbx-update -FullView off to undo)' -Encoding ASCII } catch { } }
elseif ($FullView -eq 'off') { try { Remove-Item -LiteralPath $marker -Force -ErrorAction SilentlyContinue; & $git -C $vault checkout -q -- .obsidian/app.json 2>$null | Out-Null } catch { } }
$before = (& $git -C $vault rev-parse --short HEAD 2>$null)
