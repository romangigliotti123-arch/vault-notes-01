#region vault-clean (only in vault-update.ps1; logic for /rbx-clean)
# -Clean: make the vault an EXACT copy of origin/main: fetch, reset --hard, git clean -fd (never -x) with explicit excludes for everything protected
# (My Research/, every folder holding PROTECTED-RESEARCH.md, .full-view, Assets/, .obsidian/workspace*). DESTRUCTIVE: prints a dry run first and applies only with -Yes
# (or after an interactive "yes"). Before deleting it saves a patch of your tracked edits + a list (clean-removed-<ts>.patch/.list.txt, newest 5) and copies the untracked
# files it will remove to <state>\clean-backup-<ts> (newest 3, max 500 MB; a backup that would be bigger is skipped and said so). -IncludeMine also deletes My Research\
# (only when its backup succeeded).
function Get-TreeInfo([string]$p) {
  $fs = @(Get-ChildItem -LiteralPath $p -Recurse -File -Force -ErrorAction SilentlyContinue)
  if (Test-Path -LiteralPath $p -PathType Leaf) { $fs = @(Get-Item -LiteralPath $p -Force) }
  $b = 0; foreach ($f in $fs) { $b += $f.Length }
  return [pscustomobject]@{ Files = $fs.Count; Bytes = [long]$b }
}
function Copy-ToBackup([string]$vault, [string]$bk, [string]$rel) {
  $src = Join-Path $vault $rel
  $dst = Join-Path $bk $rel
  New-Item -ItemType Directory -Force (Split-Path $dst -Parent) | Out-Null
  Copy-Item -LiteralPath $src -Destination $dst -Recurse -Force -ErrorAction SilentlyContinue
  return ((Get-TreeInfo $src).Files -eq (Get-TreeInfo $dst).Files)
}
function Write-Capped([string]$head, $lines, [int]$max) {
  $lines = @($lines)
  Write-Output "$head ($($lines.Count))"
  foreach ($l in ($lines | Select-Object -First $max)) { Write-Output "  $l" }
  if ($lines.Count -gt $max) { Write-Output "  ... and $($lines.Count - $max) more" }
}
function Invoke-CleanVault {
  param([string]$git, [string]$vault, [string]$state, [bool]$yes, [bool]$includeMine)
  $ErrorActionPreference = 'Continue'
  $tag = 'rbx-clean'
  $script:CleanApplied = $false
  & $git -C $vault config core.autocrlf false 2>$null | Out-Null
  & $git -C $vault config core.safecrlf false 2>$null | Out-Null
  & $git -C $vault config core.longpaths true 2>$null | Out-Null
  $prot = @(Protect-Vault $git $vault)
  & $git -C $vault fetch -q origin 2>$null | Out-Null
  if ($LASTEXITCODE -ne 0) { Write-Output "${tag}: fetch failed (offline?), nothing changed"; return }
  $t = 'origin/main'
  & $git -C $vault rev-parse -q --verify $t 2>$null | Out-Null
  if ($LASTEXITCODE -ne 0) { Write-Output "${tag}: no origin/main, nothing changed"; return }
  & $git -C $vault update-index -q --refresh 2>$null | Out-Null
  $keep = @($prot | Where-Object { -not $includeMine -or ($_ -ne 'My Research' -and -not $_.StartsWith('My Research/')) })
  $ex = @('-e', '/.full-view', '-e', '/Assets/', '-e', '/.obsidian/workspace*')
  foreach ($d in $keep) { $ex += @('-e', "/$d/") }
  $cl = @(& $git -C $vault -c core.quotepath=false clean -nd @ex 2>$null | ForEach-Object { $_ -replace '^Would remove ', '' })
  $local = @(& $git -C $vault -c core.quotepath=false status --porcelain --untracked-files=no 2>$null)
  $up = @(& $git -C $vault -c core.quotepath=false diff --name-status HEAD $t 2>$null)
  $mineDir = Join-Path $vault 'My Research'
  $mine = $null; if ($includeMine -and (Test-Path -LiteralPath $mineDir -PathType Container)) { $mine = Get-TreeInfo $mineDir }
  Write-Output "${tag}: DRY RUN, nothing has been changed yet. Target: exact copy of $t ($((& $git -C $vault rev-parse --short $t).Trim()))."
  Write-Capped 'Your edits to tracked files that would be reset (saved to a patch first)' $local 30
  Write-Capped 'Files the update would change/add/remove to match the main vault' $up 30
  Write-Capped 'Your own untracked files that would be deleted (copied to a backup first)' $cl 40
  Write-Output ('Kept untouched: ' + (($keep | ForEach-Object { "$_/" }) -join ', ') + $(if ($keep.Count) { ', ' }) + 'Assets/ (synced separately), .full-view, .obsidian/workspace*')
  if ($includeMine) {
    if ($mine) {
      $names = @(Get-ChildItem -LiteralPath $mineDir -Force -ErrorAction SilentlyContinue | ForEach-Object { $_.Name }) -join ', '
      Write-Output ("WARNING -IncludeMine: My Research\ WILL BE DELETED too: {0} files, {1:N1} MB ({2}). A backup copy is made first; if the backup fails, My Research is kept." -f $mine.Files, ($mine.Bytes / 1MB), $names)
    } else { Write-Output 'WARNING -IncludeMine: there is no My Research folder, nothing extra to delete.' }
  }
  if (-not $yes) {
    if (-not [Console]::IsInputRedirected -and [Environment]::UserInteractive) {
      $a = Read-Host 'Type yes to apply this clean update'
      if ($a -ne 'yes') { Write-Output "${tag}: cancelled, nothing changed"; return }
    } else {
      Write-Output "${tag}: NOT APPLIED. Re-run with -Yes to apply (powershell -NoProfile -ExecutionPolicy Bypass -File `"$vault\vault-update.ps1`" -Clean -Yes)."
      return
    }
  }
  # --- apply ---
  New-Item -ItemType Directory -Force $state | Out-Null
  $ts = Get-Date -Format 'yyyyMMdd-HHmmss'
  $capBytes = 500MB
  if ($local.Count -gt 0) { & $git -C $vault diff HEAD --binary "--output=$(Join-Path $state "clean-removed-$ts.patch")" 2>$null | Out-Null }
  Set-Content -LiteralPath (Join-Path $state "clean-removed-$ts.list.txt") -Value (@($local) + @($up) + @($cl | ForEach-Object { "untracked: $_" })) -Encoding UTF8
  $items = @($cl | ForEach-Object { $_.TrimEnd('/') })
  if ($mine) { $items += 'My Research' }
  $total = 0; foreach ($i in $items) { $total += (Get-TreeInfo (Join-Path $vault $i)).Bytes }
  $bk = Join-Path $state "clean-backup-$ts"
  $backupOk = $true; $mineOk = $true; $backupNote = $null
  if ($items.Count -eq 0) { $backupNote = 'no untracked files to back up' }
  elseif ($total -gt $capBytes) {
    $backupOk = $false; $mineOk = $false
    $backupNote = ("backup of your untracked files SKIPPED: {0:N0} MB is over the 500 MB cap" -f ($total / 1MB)) + $(if ($mine) { '; My Research is NOT deleted' } else { '' })
  } else {
    foreach ($i in $items) {
      if (-not (Copy-ToBackup $vault $bk $i)) { $backupOk = $false; if ($i -eq 'My Research') { $mineOk = $false } }
    }
    $backupNote = if ($backupOk) { "untracked files copied to $bk" } else { "backup incomplete in $bk" + $(if ($mine) { '; My Research is NOT deleted' } else { '' }) }
  }
  foreach ($pat in 'clean-removed-*.patch', 'clean-removed-*.list.txt') {
    Get-ChildItem -LiteralPath $state -Filter $pat -ErrorAction SilentlyContinue | Sort-Object Name -Descending | Select-Object -Skip 5 | Remove-Item -Force -ErrorAction SilentlyContinue
  }
  $bks = @(Get-ChildItem -LiteralPath $state -Directory -Filter 'clean-backup-*' -ErrorAction SilentlyContinue | Sort-Object Name -Descending)
  foreach ($o in ($bks | Select-Object -Skip 3)) { Remove-Item -LiteralPath $o.FullName -Recurse -Force -ErrorAction SilentlyContinue }
  $bks = @(Get-ChildItem -LiteralPath $state -Directory -Filter 'clean-backup-*' -ErrorAction SilentlyContinue | Sort-Object Name -Descending)
  while ($bks.Count -gt 1) {
    $sum = 0; foreach ($o in $bks) { $sum += (Get-TreeInfo $o.FullName).Bytes }
    if ($sum -le $capBytes) { break }
    Remove-Item -LiteralPath $bks[-1].FullName -Recurse -Force -ErrorAction SilentlyContinue
    $bks = @($bks | Select-Object -First ($bks.Count - 1))
  }
  & $git -C $vault reset --hard -q $t 2>$null | Out-Null
  if ($LASTEXITCODE -ne 0) { Write-Output "${tag}: could not reset the vault (left as it is, backups in $state)"; return }
  & $git -C $vault clean -fdq @ex 2>$null | Out-Null
  $mineMsg = ''
  if ($mine -and $mineOk) { Remove-Item -LiteralPath $mineDir -Recurse -Force -ErrorAction SilentlyContinue; $mineMsg = ' My Research deleted (backup kept).' }
  try { if (Test-Path -LiteralPath (Join-Path $vault '.full-view')) { Set-FullViewConfig $vault } } catch { }
  Write-Output ("${tag}: vault is now an exact copy of $t ($((& $git -C $vault rev-parse --short HEAD).Trim())); removed {0} untracked item(s); $backupNote; tracked-edit patch + list in $state (clean-removed-$ts.*).$mineMsg" -f $cl.Count)
  $script:CleanApplied = $true; return
}
